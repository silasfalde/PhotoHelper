#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
FUNCTIONS_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/photohelper"
FUNCTIONS_FILE="$FUNCTIONS_DIR/shell-functions.sh"

case "${1:-}" in
    "")
        ;;
    bash)
        SHELL_NAME=bash
        ;;
    zsh)
        SHELL_NAME=zsh
        ;;
    *)
        printf 'Usage: %s [bash|zsh]\n' "$0" >&2
        exit 2
        ;;
esac

if [[ -z "${SHELL_NAME:-}" ]]; then
    SHELL_NAME="$(basename -- "${SHELL:-}")"
fi

case "$SHELL_NAME" in
    bash)
        SHELL_CONFIG="$HOME/.bashrc"
        ;;
    zsh)
        SHELL_CONFIG="$HOME/.zshrc"
        ;;
    *)
        printf 'Unsupported shell: %s. Specify bash or zsh explicitly.\n' "$SHELL_NAME" >&2
        exit 1
        ;;
esac

mkdir -p -- "$FUNCTIONS_DIR"

{
    printf '# Generated by %s; do not edit.\n' "$0"
    printf '# Regenerate with: %s\n\n' "$PROJECT_ROOT/scripts/install-shell-functions.sh"

    while IFS= read -r script; do
        script_name="$(basename -- "$script" .sh)"
        printf '%s() {\n' "$script_name"
        printf '    %q "$@"\n' "$script"
        printf '}\n\n'
    done < <(
        find "$SCRIPT_DIR" -maxdepth 1 -type f -name '*.sh' \
            ! -name 'activate-photohelper.sh' \
            ! -name 'install-shell-functions.sh' \
            -print | sort
    )
} > "$FUNCTIONS_FILE"

source_command="source $(printf '%q' "$FUNCTIONS_FILE")"
if [[ ! -f "$SHELL_CONFIG" ]] || ! grep -Fqx "$source_command" "$SHELL_CONFIG"; then
    {
        printf '\n# PhotoHelper shell functions\n'
        printf '%s\n' "$source_command"
    } >> "$SHELL_CONFIG"
fi

printf 'Installed PhotoHelper shell functions for %s in %s:\n' "$SHELL_NAME" "$SHELL_CONFIG"
while IFS= read -r script; do
    printf '  %s\n' "$(basename -- "$script" .sh)"
done < <(
    find "$SCRIPT_DIR" -maxdepth 1 -type f -name '*.sh' \
        ! -name 'activate-photohelper.sh' \
        ! -name 'install-shell-functions.sh' \
        -print | sort
)
printf '\nReload your shell or run: %s\n' "$source_command"
